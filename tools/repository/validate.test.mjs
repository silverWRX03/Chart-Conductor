import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { repositoryRoot, trackedFiles, validate } from './validate.mjs';

const originals = trackedFiles(repositoryRoot);
function scenario(change, check) {
  const prefix = path.join(os.tmpdir(), 'chart-conductor-policy-');
  const dir = fs.mkdtempSync(prefix);
  const files = [...originals];
  const write = (p, content) => {
    fs.mkdirSync(path.dirname(path.join(dir, p)), { recursive: true });
    fs.writeFileSync(path.join(dir, p), content);
    if (!files.includes(p)) files.push(p);
  };
  const replace = (p, a, b) => write(p, fs.readFileSync(path.join(dir, p), 'utf8').replace(a, b));
  try {
    for (const p of originals) write(p, fs.readFileSync(path.join(repositoryRoot, p)));
    change({ files, write, replace });
    check(validate(dir, files));
  } finally {
    // This computed recursive cleanup is restricted to this exact temp prefix.
    if (!path.resolve(dir).startsWith(path.resolve(prefix)) ||
      path.dirname(path.resolve(dir)) !== path.resolve(os.tmpdir())) throw Error('Unsafe temp cleanup');
    fs.rmSync(dir, { recursive: true, force: true });
  }
}
const rejects = (pattern) => (errors) => assert.ok(errors.some((e) => pattern.test(e)), errors.join('\n'));
test('clean proposed tree passes', () => scenario(() => {}, (errors) => assert.deepEqual(errors, [])));
test('missing required policy fails', () => scenario(({ files }) => files.splice(files.indexOf('SECURITY.md'), 1), rejects(/Required file/)));
test('broken local link fails', () => scenario(({ write }) => write('probe.md', '# Probe\n\n[Missing](absent.md)\n'), rejects(/Broken internal link/)));
test('broken heading fails', () => scenario(({ write }) => write('probe.md', '# Probe\n\n[Missing](README.md#absent)\n'), rejects(/Broken heading/)));
test('duplicate YAML keys fail', () => scenario(({ write }) => write('probe.yml', 'name: first\nname: second\n'), rejects(/Invalid or ambiguous YAML/)));
test('duplicate issue IDs fail', () => scenario(({ replace }) => replace('.github/ISSUE_TEMPLATE/bug_report.yml', 'id: platform', 'id: revision'), rejects(/duplicate form ID/)));
test('unpinned Action fails', () => scenario(({ replace }) => replace('.github/workflows/repository-validation.yml', /actions\/checkout@[a-f0-9]{40}/, 'actions/checkout@main'), rejects(/full commit SHA/)));
test('persisted checkout credentials fail', () => scenario(({ replace }) => replace('.github/workflows/repository-validation.yml', 'persist-credentials: false', 'persist-credentials: true'), rejects(/persisted credentials/)));
test('tracked ignored music fails', () => scenario(({ write }) => write('songs/private.mp3', 'synthetic test bytes'), rejects(/Forbidden tracked data/)));
test('unlisted fixture fails', () => scenario(({ write }) => write('tests/fixtures/example.mid', 'synthetic test bytes'), rejects(/not rights-allowlisted/)));
